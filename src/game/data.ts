export function getPropertyConfig(
  location: SafeHouseConfig['location'],
  type: PropertyTypeConfig['id'],
): PropertyConfig {
  const base = SAFE_HOUSE_BY_LOCATION[location]
  const config = PROPERTY_TYPE_BY_ID[type]
  return {
    location,
    type,
    name: type === 'stash' ? base.name : config.name,
    cost: Math.max(100, Math.round((base.cost * config.costMultiplier) / 50) * 50),
    storage: Math.max(
      10,
      Math.round((base.storage * config.storageMultiplier) / 10) * 10,
    ),
    growSlots: config.growSlots ?? base.growSlots,
    blurb: config.blurb,
  }
}
